#!/usr/bin/env python3
"""Bootstraps a fresh Porch for the conformance run through its management API (stdlib only).

Completes first-time setup with the setup token, registers the fake Google provider, a tenant whose Workspace-domain
rule enrolls ada@smith.example on first login, and three confidential OIDC applications: "client" and "client2" in the
suite's terms, plus "client_secret_post" (the static client the oidcc-server-client-secret-post module authenticates
with client_secret_post). Prints a JSON object with the clients' credentials on stdout.

Porch is reached on a loopback port published by docker compose while every request carries the Host/Origin of its
public URL (https://porch:8443), so the CSRF/Origin checks see the real public origin. TLS verification is off: the
certificate is a throwaway self-signed one generated by run.sh.
"""

import argparse
import http.client
import json
import ssl
import sys

ap = argparse.ArgumentParser()
ap.add_argument("--connect", required=True, help="host:port to connect to (published Porch port)")
ap.add_argument("--public-url", required=True, help="Porch public_url / issuer, e.g. https://porch:8443")
ap.add_argument("--token", required=True, help="setup token")
ap.add_argument("--idp-issuer", required=True)
ap.add_argument("--idp-client-id", required=True)
ap.add_argument("--idp-client-secret", required=True)
ap.add_argument("--redirect-uri", required=True, help="the suite's callback URL")
ap.add_argument("--post-logout-uri", required=True)
args = ap.parse_args()

host = args.public_url.split("://", 1)[1].rstrip("/")
ctx = ssl.create_default_context()
ctx.check_hostname = False
ctx.verify_mode = ssl.CERT_NONE
cookies: dict[str, str] = {}
csrf = ""


def call(method: str, path: str, body=None):
    global csrf
    h, p = args.connect.rsplit(":", 1)
    conn = http.client.HTTPSConnection(h, int(p), context=ctx, timeout=30)
    headers = {"Host": host, "Origin": args.public_url, "Accept": "application/json"}
    if body is not None:
        headers["Content-Type"] = "application/json"
    if csrf:
        headers["X-Porch-CSRF"] = csrf
    if cookies:
        headers["Cookie"] = "; ".join(f"{k}={v}" for k, v in cookies.items())
    conn.request(method, "/api/v1" + path, body=None if body is None else json.dumps(body), headers=headers)
    resp = conn.getresponse()
    raw = resp.read()
    for name, value in resp.getheaders():
        if name.lower() == "set-cookie":
            k, _, rest = value.partition("=")
            cookies[k.strip()] = rest.split(";", 1)[0]
    if resp.status >= 300:
        sys.exit(f"bootstrap: {method} {path} -> HTTP {resp.status}: {raw.decode(errors='replace')}")
    return json.loads(raw) if raw else None


me = call("POST", "/setup", {"token": args.token, "display_name": "Conformance Owner"})
csrf = me["csrf_token"]
prov = call("POST", "/identity-providers", {"slug": "google", "kind": "google", "name": "Google", "issuer": args.idp_issuer,
                                            "client_id": args.idp_client_id, "client_secret": args.idp_client_secret})
call("POST", "/tenants", {"slug": "smith", "name": "Smith family"})
call("POST", "/tenants/smith/domain-rules", {"domain": "smith.example", "provider_id": prov["id"],
                                             "evidence_kind": "workspace_hd", "mode": "jit"})
out = {}
for key, slug in (("client", "conformance-1"), ("client2", "conformance-2"), ("client_secret_post", "conformance-post")):
    app = call("POST", "/tenants/smith/applications", {
        "slug": slug, "name": f"Conformance {key}", "kind": "oidc",
        "client": {"client_type": "confidential", "redirect_uris": [args.redirect_uri],
                   "post_logout_redirect_uris": [args.post_logout_uri],
                   "grant_types": ["authorization_code", "refresh_token"], "require_pkce": False},
        "disclosure": {"email": True, "groups": False, "roles": True, "entitlements": False},
    })
    out[key] = {"client_id": app["client"]["client_id"], "client_secret": app["client_secret"],
                "signing_alg": app["client"].get("signing_alg"), "allowed_scopes": app["client"].get("allowed_scopes")}
json.dump(out, sys.stdout)
